DECLARE cols text := '';
BEGIN
    FOR i IN 1..40 LOOP
        cols := cols || format(', metric_%s numeric(10,3)', lpad(i::text, 2, '0'));
    END LOOP;
    EXECUTE 'CREATE TABLE shop.wide_metrics (id integer PRIMARY KEY, label text' || cols || ')';
