-- pgtui demo schema: covers the object kinds and data types the client must handle.

CREATE SCHEMA shop;
COMMENT ON SCHEMA shop IS 'Boutique en ligne de démonstration';
CREATE SCHEMA hr;
COMMENT ON SCHEMA hr IS 'Ressources humaines';
CREATE SCHEMA audit;

-- ---------------------------------------------------------------- shop
CREATE TYPE shop.order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled');

CREATE TABLE shop.customers (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id   uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    email       text NOT NULL UNIQUE CHECK (email LIKE '%@%'),
    full_name   text NOT NULL,
    country     char(2) NOT NULL DEFAULT 'FR',
    birth_date  date,
    created_at  timestamptz NOT NULL DEFAULT now(),
    is_active   boolean NOT NULL DEFAULT true,
    balance     numeric(12, 2) NOT NULL DEFAULT 0,
    preferences jsonb,
    tags        text[],
    last_ip     inet,
    avatar      bytea,
    notes       text
);
COMMENT ON TABLE shop.customers IS 'Clients de la boutique';
COMMENT ON COLUMN shop.customers.public_id IS 'Identifiant exposé dans l''API';
COMMENT ON COLUMN shop.customers.preferences IS 'Préférences utilisateur (JSON libre)';
CREATE INDEX customers_country_idx ON shop.customers (country);
CREATE INDEX customers_tags_idx ON shop.customers USING gin (tags);

CREATE TABLE shop.products (
    id          serial PRIMARY KEY,
    sku         varchar(32) NOT NULL UNIQUE,
    name        text NOT NULL,
    description text,
    price       numeric(10, 2) NOT NULL CHECK (price > 0),
    stock       integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
    weight_kg   real,
    attributes  jsonb NOT NULL DEFAULT '{}',
    released_on date,
    updated_at  timestamp NOT NULL DEFAULT now()
);
COMMENT ON TABLE shop.products IS 'Catalogue produits';
CREATE INDEX products_attributes_idx ON shop.products USING gin (attributes jsonb_path_ops);

CREATE FUNCTION shop.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;
CREATE TRIGGER products_touch BEFORE UPDATE ON shop.products
    FOR EACH ROW EXECUTE FUNCTION shop.touch_updated_at();

CREATE TABLE shop.orders (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     bigint NOT NULL REFERENCES shop.customers (id) ON DELETE CASCADE,
    status          shop.order_status NOT NULL DEFAULT 'pending',
    ordered_at      timestamptz NOT NULL DEFAULT now(),
    shipped_at      timestamp,
    processing_time interval,
    total           numeric(12, 2) NOT NULL DEFAULT 0,
    notes           text
);
CREATE INDEX orders_customer_idx ON shop.orders (customer_id);
CREATE INDEX orders_status_date_idx ON shop.orders (status, ordered_at DESC);

CREATE TABLE shop.order_items (
    order_id   bigint NOT NULL REFERENCES shop.orders (id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES shop.products (id),
    quantity   integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL,
    PRIMARY KEY (order_id, product_id)
);
COMMENT ON TABLE shop.order_items IS 'Lignes de commande (clé primaire composite)';

CREATE SEQUENCE shop.invoice_number_seq START 1000;

CREATE VIEW shop.v_order_totals AS
SELECT o.id, c.full_name, o.status, o.ordered_at, sum(i.quantity * i.unit_price) AS computed_total
FROM shop.orders o
JOIN shop.customers c ON c.id = o.customer_id
JOIN shop.order_items i ON i.order_id = o.id
GROUP BY o.id, c.full_name;
COMMENT ON VIEW shop.v_order_totals IS 'Total recalculé par commande';

CREATE MATERIALIZED VIEW shop.mv_daily_sales AS
SELECT date_trunc('day', ordered_at)::date AS day, count(*) AS orders, sum(total) AS revenue
FROM shop.orders
GROUP BY 1;

CREATE FUNCTION shop.order_total(p_order_id bigint) RETURNS numeric
LANGUAGE sql STABLE AS $$
    SELECT coalesce(sum(quantity * unit_price), 0) FROM shop.order_items WHERE order_id = p_order_id
$$;
COMMENT ON FUNCTION shop.order_total(bigint) IS 'Somme des lignes d''une commande';

CREATE PROCEDURE shop.recompute_totals()
LANGUAGE sql AS $$
    UPDATE shop.orders o SET total = shop.order_total(o.id)
$$;

-- No primary key: must be shown as read-only in the Data tab.
CREATE TABLE shop.event_log (
    happened_at timestamptz NOT NULL DEFAULT now(),
    level       text NOT NULL,
    message     text
);

-- Partitioned table (partitions are hidden in the tree).
CREATE TABLE shop.measurements (
    id        bigint GENERATED ALWAYS AS IDENTITY,
    sensor    text NOT NULL,
    taken_on  date NOT NULL,
    value     double precision,
    PRIMARY KEY (id, taken_on)
) PARTITION BY RANGE (taken_on);
CREATE TABLE shop.measurements_2025 PARTITION OF shop.measurements
    FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE shop.measurements_2026 PARTITION OF shop.measurements
    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

